'use strict';

/**
 * First-run setup: generates a random admin password, stores its bcrypt
 * hash as PASSWORD_HASH in the project .env, and prints the password ONCE.
 *
 * Usage:
 *   node src/setup-password.mjs           # add PASSWORD_HASH to .env
 *   node src/setup-password.mjs --force   # replace existing PASSWORD_HASH
 *
 * ENV_PATH env var overrides the .env location (used by tests).
 */

import bcrypt from 'bcryptjs';
import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const envPath = process.env.ENV_PATH
  || path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '.env');
const force = process.argv.includes('--force');

const generatePassword = () => randomBytes(9).toString('base64url');

const main = async () => {
  const content = fs.existsSync(envPath)
    ? fs.readFileSync(envPath, 'utf8')
    : '';

  const hasPassword = /^PASSWORD_HASH=/m.test(content);
  if (hasPassword && !force) {
    // eslint-disable-next-line no-console
    console.log('PASSWORD_HASH is already set in .env — nothing to do. Use --force to regenerate.');
    return;
  }

  const password = generatePassword();
  const hash = await bcrypt.hash(password, await bcrypt.genSalt(12));

  const line = `PASSWORD_HASH='${hash}'`;
  const next = hasPassword
    ? content.replace(/^PASSWORD_HASH=.*$/m, line)
    : `${content.trimEnd()}\n\n# Generated by setup-password.mjs\n${line}\n`;

  fs.writeFileSync(envPath, next, 'utf8');

  // eslint-disable-next-line no-console
  console.log(`Admin password: ${password}\n(stored as PASSWORD_HASH in ${envPath}; restart the container to apply)`);
};

main().catch((err) => {
  // eslint-disable-next-line no-console
  console.error(err);
  // eslint-disable-next-line no-process-exit
  process.exit(1);
});
